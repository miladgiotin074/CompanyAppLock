#!/usr/bin/env node
/*
 * Bootstrap-address tool for the Android client.
 *
 * The client ships ONE compiled-in fallback server address, encrypted with
 * RSA-OAEP(SHA-256) inside app/src/main/assets/config.json, so the domain is
 * not in plaintext in the APK. On first launch the app decrypts it and talks to
 * that server; once the panel announces a new address over FCM, the cached
 * address wins for good (see ServerConfig / AppFcmService).
 *
 * Usage:
 *   node tools/encrypt-bootstrap.mjs <https://server/api/v1>
 *       Re-encrypt the bootstrap address into config.json using the EXISTING
 *       key (tools/bootstrap-public.pem). The embedded private key is unchanged,
 *       so the already-built/installed app can still decrypt it. Use this to
 *       change the initial domain.
 *
 *   node tools/encrypt-bootstrap.mjs --rotate <https://server/api/v1>
 *       Generate a NEW RSA keypair, rewrite BootstrapConfig.kt (embedded private
 *       key) + tools/bootstrap-public.pem, and encrypt the address. Use this to
 *       rotate the key (requires rebuilding + reinstalling the app).
 *
 * Only the PUBLIC key is needed to change the address — that is the whole point
 * of using RSA here. Encryption always uses OAEP with SHA-256 for both the OAEP
 * digest and MGF1, matching the Android Cipher parameters in BootstrapConfig.kt.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ANDROID = path.resolve(here, '..');
const APP = path.join(ANDROID, 'app');
const PUB_PEM = path.join(here, 'bootstrap-public.pem');
const CONFIG = path.join(APP, 'src', 'main', 'assets', 'config.json');
const KT = path.join(
  APP, 'src', 'main', 'java', 'com', 'company', 'applock', 'core', 'BootstrapConfig.kt',
);

const OAEP = { padding: crypto.constants.RSA_PKCS1_OAEP_PADDING, oaepHash: 'sha256' };

const args = process.argv.slice(2);
const rotate = args.includes('--rotate');

// Parse: [--rotate] [--port <code>] <url>
let portArg = '';
const positional = [];
for (let i = 0; i < args.length; i += 1) {
  const a = args[i];
  if (a === '--rotate') continue;
  if (a === '--port') {
    portArg = String(args[i + 1] || '').trim();
    i += 1;
    continue;
  }
  if (a.startsWith('--')) continue;
  positional.push(a);
}
const url = positional[0];

if (!url || !/^https?:\/\/.+/.test(url)) {
  console.error('Usage: node tools/encrypt-bootstrap.mjs [--rotate] [--port <20-char-code>] <http(s)://server/api/v1>');
  process.exit(1);
}
if (portArg && !/^[A-Za-z0-9]{20}$/.test(portArg)) {
  console.error('--port must be a 20-char A-Za-z0-9 code');
  process.exit(1);
}

function kotlinSource(privDerB64) {
  return [
    'package com.company.applock.core',
    '',
    'import android.content.Context',
    'import android.util.Base64',
    'import java.security.KeyFactory',
    'import java.security.spec.MGF1ParameterSpec',
    'import java.security.spec.PKCS8EncodedKeySpec',
    'import javax.crypto.Cipher',
    'import javax.crypto.spec.OAEPParameterSpec',
    'import javax.crypto.spec.PSource',
    'import org.json.JSONObject',
    '',
    '/**',
    ' * Compiled-in BOOTSTRAP server address. The real address lives in',
    ' * assets/config.json, RSA-OAEP(SHA-256)-encrypted so it is not shipped in',
    ' * plaintext. On first launch the app decrypts it and talks to that server;',
    ' * once the panel announces a new address over FCM, the cached address wins',
    ' * for good (see ServerConfig).',
    ' *',
    ' * NOTE: the decryption key is embedded below, so this is OBFUSCATION, not',
    ' * secrecy — a determined reverse-engineer can still recover the domain. The',
    ' * trust anchor for address CHANGES is FCM (authenticated by Firebase).',
    ' *',
    ' * GENERATED by tools/encrypt-bootstrap.mjs — do not edit by hand. Rerun that',
    ' * tool to change the bootstrap address or (with --rotate) rotate the key.',
    ' */',
    'object BootstrapConfig {',
    '    // PKCS#8 private key (DER, base64). Paired with tools/bootstrap-public.pem.',
    '    private const val PRIVATE_KEY =',
    '        "' + privDerB64 + '"',
    '',
    '    @Volatile private var cached: String? = null',
    '    @Volatile private var loaded = false',
    '',
    '    /** Decrypted bootstrap URL, or null if missing/invalid. Read once, memoized. */',
    '    fun serverUrl(ctx: Context): String? {',
    '        if (loaded) return cached',
    '        synchronized(this) {',
    '            if (loaded) return cached',
    '            cached = runCatching { decryptFromAssets(ctx) }.getOrNull()',
    '                ?.trim()?.trimEnd(\'/\')?.takeIf { it.isNotBlank() }',
    '            loaded = true',
    '            return cached',
    '        }',
    '    }',
    '',
    '    private fun decryptFromAssets(ctx: Context): String? {',
    '        val raw = ctx.assets.open("config.json")',
    '            .bufferedReader(Charsets.UTF_8).use { it.readText() }',
    '        val ct = JSONObject(raw).optString("server", "")',
    '        if (ct.isBlank()) return null',
    '        val keyBytes = Base64.decode(PRIVATE_KEY, Base64.DEFAULT)',
    '        val priv = KeyFactory.getInstance("RSA").generatePrivate(PKCS8EncodedKeySpec(keyBytes))',
    '        val cipher = Cipher.getInstance("RSA/ECB/OAEPPadding")',
    '        val spec = OAEPParameterSpec(',
    '            "SHA-256", "MGF1", MGF1ParameterSpec.SHA256, PSource.PSpecified.DEFAULT,',
    '        )',
    '        cipher.init(Cipher.DECRYPT_MODE, priv, spec)',
    '        val plain = cipher.doFinal(Base64.decode(ct, Base64.DEFAULT))',
    '        return String(plain, Charsets.UTF_8)',
    '    }',
    '}',
    '',
  ].join('\n');
}

let publicKeyPem;
let privateKey = null;

if (rotate || !fs.existsSync(PUB_PEM) || !fs.existsSync(KT)) {
  const pair = crypto.generateKeyPairSync('rsa', { modulusLength: 2048 });
  publicKeyPem = pair.publicKey.export({ type: 'spki', format: 'pem' });
  privateKey = pair.privateKey;
  const privDerB64 = pair.privateKey.export({ type: 'pkcs8', format: 'der' }).toString('base64');
  fs.writeFileSync(PUB_PEM, publicKeyPem);
  fs.mkdirSync(path.dirname(KT), { recursive: true });
  fs.writeFileSync(KT, kotlinSource(privDerB64));
  console.log(rotate ? '• rotated keypair → BootstrapConfig.kt rewritten' : '• generated keypair → BootstrapConfig.kt created');
} else {
  publicKeyPem = fs.readFileSync(PUB_PEM, 'utf8');
}

const ciphertext = crypto
  .publicEncrypt({ key: publicKeyPem, ...OAEP }, Buffer.from(url, 'utf8'))
  .toString('base64');

// Preserve the existing port code (the client's channel) unless --port overrides
// it, so re-encrypting the server address never drops the port again.
let port = '';
try {
  port = String(JSON.parse(fs.readFileSync(CONFIG, 'utf8')).port || '').trim();
} catch {
  port = '';
}
if (portArg) port = portArg;

const out = { v: 1, alg: 'RSA-OAEP-SHA256', server: ciphertext };
if (port) out.port = port;

fs.mkdirSync(path.dirname(CONFIG), { recursive: true });
fs.writeFileSync(CONFIG, JSON.stringify(out, null, 2) + '\n');
console.log('• port =', port || '(none)');

// Round-trip self-check when we hold the private key (confirms the OAEP params).
if (privateKey) {
  const back = crypto
    .privateDecrypt({ key: privateKey, ...OAEP }, Buffer.from(ciphertext, 'base64'))
    .toString('utf8');
  if (back !== url) {
    console.error('✗ round-trip mismatch:', back);
    process.exit(2);
  }
  console.log('✓ round-trip OK (decrypted back to the same URL)');
}

console.log('• wrote', path.relative(ANDROID, CONFIG));
console.log('• bootstrap url =', url, '(ciphertext', ciphertext.length, 'chars)');
